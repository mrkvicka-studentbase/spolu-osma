from fractions import Fraction as F
def eq(a,b,m): assert a==b, f"{m}: {a}!={b}"
def S(w,c,j): return w+F(c,j)
eq(S(2,5,9),F(23,9),'A'); eq(F(2+5,9),F(7,9),'A scit'); eq(F(2*5,9),F(10,9),'A souc')
eq(F(26,7),S(3,5,7),'B'); assert divmod(26,7)==(3,5)
eq(6-S(3,2,9),S(2,7,9),'C'); eq(F(6-3-1)+F(2,9),S(2,2,9),'C spatne'); eq(F(6-3)+F(2,9),S(3,2,9),'C po castech')
eq(S(1,3,7)*S(2,1,5),S(3,1,7),'D'); eq(1*2+F(3,7)*F(1,5),S(2,3,35),'D po'); assert divmod(22,7)==(3,1)
eq(S(3,5,6),F(23,6),'or'); eq(F(31,8),S(3,7,8),'or'); eq(7-S(4,1,3),S(2,2,3),'or')
eq(4-S(1,2,3),S(2,1,3),'red')
a=S(5,1,6); b=S(2,3,4); eq(a,F(62,12),'a'); eq(b,F(33,12),'b'); eq(a-b,S(2,5,12),'U2')
eq(F(62,12)-F(2+9,12),F(51,12),'Petr'); eq(F(51,12),S(4,1,4),'Petr4')
eq(F(5-2)+F(9,12)-F(2,12),S(3,7,12),'po castech'); eq(F(62,12)-F(18,12),S(3,2,3),'soucin'); eq(F(5+2,12),F(7,12),'k2c')
eq(S(4,1,3)-S(2,5,6),S(1,1,2),'or u2'); eq(F(26,6)-F(7,6),F(19,6),'petr or'); eq(S(2,3,4),F(11,4),'red u2')
v=S(2,1,2)*S(1,3,4); eq(v,F(35,8),'k2'); eq(v,S(4,3,8),'k2m'); eq(2*1+F(1,2)*F(3,4),S(2,3,8),'po')
eq(10-v,S(5,5,8),'fin'); eq(10-S(2,3,8),S(7,5,8),'fin po'); eq(F(10-4-1)+F(3,8),S(5,3,8),'fin spatne'); eq(F(10-4)+F(3,8),S(6,3,8),'fin po cast')
eq(S(1,1,4)*S(2,2,5),3,'or u3'); eq(7-S(3,2,5),S(3,3,5),'or u3b'); eq(F(7,4)*4,7,'red u3')
A=S(4,1,3); B=S(1,7,8); C=S(1,1,3)
eq(A-B*C,S(1,5,6),'U4'); eq((A-B)*C,S(3,5,18),'pred'); eq(A-(1*1+F(7,8)*F(1,3)),S(3,1,24),'po'); eq(A-F(1+7,8)*F(1+1,3),S(3,2,3),'scit')
eq(S(4,1,2)-S(1,1,3)*3,F(1,2),'or u4'); eq(S(3,1,2)-S(1,1,4)*2,1,'red u4')
